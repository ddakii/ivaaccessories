export function colorLabel(value?: string) {
  if (!value) return "";
  return colors[value] ?? value;
}

export function categoryLabel(slug?: string, fallback?: string) {
  if (!slug) return fallback ?? "";
  const map: Record<string, string> = sq.categories;
  return map[slug] ?? fallback ?? slug;
}

export function genderLabel(value?: string) {
  if (!value) return "";
  return sq.gender[value] ?? value.toLowerCase();
}

export function statusLabel(value?: string) {
  if (!value) return "";
  return sq.status[value] ?? value;
}
